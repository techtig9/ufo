import type { Project } from '@/lib/types';

/**
 * Design-system generation.
 *
 * A style guide listing five hex codes is a picture of a design system, not a
 * design system. What a developer receiving a handoff actually needs is
 * something they can import: CSS custom properties, a Tailwind theme that maps
 * to them, and a machine-readable token file for whatever pipeline they run.
 * This emits all three from one source, so they cannot disagree with each
 * other or with the screens.
 *
 * Every function here is pure and takes the project's saved tokens. Nothing
 * is invented: when a project has no tokens, the export says so rather than
 * shipping a plausible-looking default palette that matches none of its
 * screens.
 */

export interface ProjectTokens {
  colors: Record<string, string>;
  fonts: { display: string | null; body: string | null };
}

/**
 * A font pairing is stored as free text ("Space Grotesk / Inter"). Split on the
 * usual separators; a single name means one family used for both roles.
 */
export function parseFontPairing(pairing: string | null): { display: string | null; body: string | null } {
  if (!pairing?.trim()) return { display: null, body: null };

  const parts = pairing
    .split(/\s*(?:\/|\+|,|—|–|\band\b)\s*/i)
    .map((p) => p.trim())
    .filter(Boolean);

  if (parts.length === 0) return { display: null, body: null };
  if (parts.length === 1) return { display: parts[0], body: parts[0] };
  return { display: parts[0], body: parts[1] };
}

export function projectTokens(project: Project): ProjectTokens {
  return {
    colors: (project.color_theme as Record<string, string> | null) ?? {},
    fonts: parseFontPairing(project.font_pairing),
  };
}

/** A CSS custom property name from a token key. */
function cssVar(key: string): string {
  return `--${key.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase()}`;
}

/**
 * A font family value safe to paste into CSS. A name with a space must be
 * quoted, and a fallback stack is appended so the page still renders before
 * the webfont loads (or if it never does).
 */
function fontStack(name: string | null, fallback: string): string {
  if (!name) return fallback;
  const quoted = /[\s'"]/.test(name) ? `"${name.replace(/"/g, '')}"` : name;
  return `${quoted}, ${fallback}`;
}

const SANS_FALLBACK = 'system-ui, -apple-system, Segoe UI, Roboto, sans-serif';

export function tokensCss(project: Project): string {
  const { colors, fonts } = projectTokens(project);

  const colorLines = Object.entries(colors)
    .map(([key, value]) => `  ${cssVar(key)}: ${value};`)
    .join('\n');

  return `/**
 * ${project.name} — design tokens
 *
 * Generated by ufo from this project's saved theme. Import this file, then
 * reference the variables rather than the literal values: changing a token
 * here should change every screen at once, which is the only reason a token
 * layer is worth having.
 */
:root {
${colorLines || '  /* This project has no saved colour theme. */'}

  --font-display: ${fontStack(fonts.display, SANS_FALLBACK)};
  --font-body: ${fontStack(fonts.body, SANS_FALLBACK)};
}
`;
}

export function tokensJson(project: Project): string {
  const { colors, fonts } = projectTokens(project);

  return `${JSON.stringify(
    {
      $schema: 'https://design-tokens.org/schema.json',
      name: project.name,
      generatedBy: 'ufo',
      color: Object.fromEntries(
        Object.entries(colors).map(([key, value]) => [key, { value, type: 'color' }])
      ),
      font: {
        display: { value: fonts.display ?? null, type: 'fontFamily' },
        body: { value: fonts.body ?? null, type: 'fontFamily' },
      },
    },
    null,
    2
  )}\n`;
}

export function tailwindPreset(project: Project): string {
  const { colors } = projectTokens(project);

  const colorEntries = Object.keys(colors)
    .map((key) => `      ${JSON.stringify(key)}: 'var(${cssVar(key)})',`)
    .join('\n');

  return `/**
 * ${project.name} — Tailwind preset
 *
 * Deliberately maps to the CSS variables in tokens.css rather than inlining
 * hex values. Inlined values mean a theme change has to be made twice and one
 * of the two is always forgotten; through a variable, tokens.css stays the
 * single source.
 *
 *   // tailwind.config.js
 *   module.exports = { presets: [require('./design-system/tailwind-preset.js')] }
 */
module.exports = {
  theme: {
    extend: {
      colors: {
${colorEntries || '        // This project has no saved colour theme.'}
      },
      fontFamily: {
        display: ['var(--font-display)'],
        body: ['var(--font-body)'],
      },
    },
  },
};
`;
}

export function designSystemReadme(project: Project): string {
  const { colors, fonts } = projectTokens(project);
  const hasTokens = Object.keys(colors).length > 0;

  return `# ${project.name} — design system

Generated by ufo from this project's saved theme.

## Files

| File | What it is |
|---|---|
| \`tokens.css\` | CSS custom properties. Import first; everything else points at these. |
| \`tailwind-preset.js\` | Tailwind theme mapping to those variables, not to hex values. |
| \`tokens.json\` | Machine-readable tokens, for a pipeline or a Figma import. |

## Use it

\`\`\`js
// tailwind.config.js
module.exports = { presets: [require('./design-system/tailwind-preset.js')] };
\`\`\`

\`\`\`css
/* your global stylesheet, before Tailwind */
@import './design-system/tokens.css';
\`\`\`

${
  hasTokens
    ? `## Colours\n\n${Object.entries(colors)
        .map(([k, v]) => `- \`${cssVar(k)}\` — \`${v}\` (${k})`)
        .join('\n')}`
    : `## Colours\n\nThis project has **no saved colour theme**, so no colour tokens were generated. Nothing was invented to fill the gap: a plausible default palette that matches none of the screens is worse than an empty file. Set a theme in the editor and export again.`
}

## Type

- Display: ${fonts.display ?? '_not set_'}
- Body: ${fonts.body ?? '_not set_'}

Both fall back to a system stack, so the screens render before a webfont loads
— or if it never does.
`;
}
